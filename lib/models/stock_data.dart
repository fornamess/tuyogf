  static int? parseNumber(String text) {
    // Обработка чисел с запятой (2,5 -> 2)
    final cleanText = text.replaceAll(',', '');
    
    if (RegExp(r'^\d+$').hasMatch(cleanText)) {
      return int.tryParse(cleanText);
    }
    return numberWords[text.toLowerCase()];
  }

  static int getValue(String stock, int row, int col) {
    // Нормализуем название акции
    String normalizedStock = stock.trim();
    
    // Попробуем найти точное совпадение
    if (tables.containsKey(normalizedStock)) {
      return _getValueFromTable(normalizedStock, row, col);
    }
    
    // Попробуем найти по первой букве заглавной
    final capitalized = normalizedStock.toLowerCase().split(' ').map((word) => 
        word.isNotEmpty ? word[0].toUpperCase() + word.substring(1) : word).join(' ');
    
    if (tables.containsKey(capitalized)) {
      return _getValueFromTable(capitalized, row, col);
    }
    
    // Попробуем найти среди всех ключей (регистронезависимо)
    for (String key in tables.keys) {
      if (key.toLowerCase() == normalizedStock.toLowerCase()) {
        return _getValueFromTable(key, row, col);
      }
    }
    
    throw Exception('Акция "$stock" не найдена. Доступные: ${tables.keys.join(', ')}');
  }
  
  static int _getValueFromTable(String stock, int row, int col) {
    if (!tables[stock]!.containsKey(row)) {
      throw Exception('Строка $row не найдена для акции "$stock".');
    }
    
    if (!tables[stock]![row]!.containsKey(col)) {
      throw Exception('Столбец $col не найден для строки $row акции "$stock".');
    }
    
    return tables[stock]![row]![col]!;
  }

  static List<String> getAvailableStocks() {
    return tables.keys.toList();
  }
